import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from google.colab import files

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix,
    roc_curve,
    auc
)

dataset = pd.read_csv('/content/heart_attack_prediction_dataset.csv')
print("Dataset Shape:", dataset.shape)
display(dataset.head())
print(dataset.info())

if 'Blood Pressure' in dataset.columns:
    dataset[['Systolic_BP', 'Diastolic_BP']] = dataset['Blood Pressure'].str.split('/', expand=True).astype(float)
    dataset = dataset.drop(columns=['Blood Pressure'])

to_drop = [col for col in ['Patient ID', 'Country'] if col in dataset.columns]
if to_drop:
    dataset = dataset.drop(columns=to_drop)

categorical_cols = [col for col in ['Sex', 'Diet', 'Continent', 'Hemisphere'] if col in dataset.columns]
if categorical_cols:
    dataset = pd.get_dummies(dataset, columns=categorical_cols, drop_first=True)

print("Processed dataset columns:", dataset.columns)
print("New shape:", dataset.shape)
display(dataset.head())

X = dataset.drop('Heart Attack Risk', axis=1)
Y = dataset['Heart Attack Risk']

X_train, X_test, Y_train, Y_test = train_test_split(
    X,
    Y,
    test_size=0.20,
    random_state=0,
    stratify=Y
)

scaler = StandardScaler()
X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

print("Training shape:", X_train.shape)
print("Testing shape:", X_test.shape)

model = LogisticRegression(random_state=0, max_iter=1000)
model.fit(X_train, Y_train)

Y_pred = model.predict(X_test)
Y_prob = model.predict_proba(X_test)[:, 1]

accuracy = accuracy_score(Y_test, Y_pred)
precision = precision_score(Y_test, Y_pred, zero_division=0)
recall = recall_score(Y_test, Y_pred, zero_division=0)
f1 = f1_score(Y_test, Y_pred, zero_division=0)

print("Logistic Regression Accuracy  :", accuracy)
print("Logistic Regression Precision :", precision)
print("Logistic Regression Recall    :", recall)
print("Logistic Regression F1 Score  :", f1)

cm = confusion_matrix(Y_test, Y_pred)
plt.figure(figsize=(6, 5))
sns.heatmap(
    cm,
    annot=True,
    fmt='d',
    cmap='Blues',
    xticklabels=['No Risk', 'Risk'],
    yticklabels=['No Risk', 'Risk']
)
plt.ylabel('Actual')
plt.xlabel('Predicted')
plt.title('Confusion Matrix')
plt.show()

plt.figure(figsize=(12, 8))
sns.heatmap(
    dataset.corr(numeric_only=True),
    annot=True,
    cmap='coolwarm',
    fmt='.2f'
)
plt.title("Feature Correlation Heatmap")
plt.show()

fpr, tpr, thresholds = roc_curve(Y_test, Y_prob)
roc_auc = auc(fpr, tpr)

plt.figure(figsize=(7, 5))
plt.plot(fpr, tpr, label=f'AUC = {roc_auc:.2f}')
plt.plot([0, 1], [0, 1], '--')
plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")
plt.title("ROC Curve")
plt.legend()
plt.show()

models = {
    "Logistic Regression": LogisticRegression(random_state=0, max_iter=1000),
    "Random Forest": RandomForestClassifier(random_state=0),
    "Gradient Boosting": GradientBoostingClassifier(random_state=0)
}

results = []
for name, clf in models.items():
    clf.fit(X_train, Y_train)
    preds = clf.predict(X_test)

    results.append({
        "Model": name,
        "Accuracy": accuracy_score(Y_test, preds),
        "Precision": precision_score(Y_test, preds, zero_division=0),
        "Recall": recall_score(Y_test, preds, zero_division=0),
        "F1 Score": f1_score(Y_test, preds, zero_division=0)
    })

df_compare = pd.DataFrame(results)
display(df_compare)

df_melted = df_compare.melt(id_vars="Model", var_name="Metric", value_name="Value")
plt.figure(figsize=(10, 6))
sns.barplot(data=df_melted, x="Metric", y="Value", hue="Model")
plt.title("Model Comparison")
plt.ylabel("Score")
plt.ylim(0, 1.1)
plt.show()

best_model_info = df_compare.sort_values(by=["F1 Score", "Accuracy"], ascending=False).iloc[0]
print(f"Best Model: {best_model_info['Model']}")
print(best_model_info)

print("All processes completed successfully.")

